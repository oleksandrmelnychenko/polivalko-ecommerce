export const ENTITY_TYPE_OPTIONS = Object.entries(entityTypeLabel).map(([value, label]) => ({ value, label }))

const entityLinks: Record<string, { permission: PermissionKey; href: (id: string) => string }> = {
  Order: { permission: PermissionKeys.Orders.View, href: (id) => `/sales/orders/${encodeURIComponent(id)}` },
  Page: { permission: PermissionKeys.Content.ManageSite, href: (id) => `/site/pages/${encodeURIComponent(id)}` },
}

export function entityHref(entityType: string, entityId: string | null, can: (permission: PermissionKey) => boolean): string | undefined {
  const link = entityLinks[entityType]
  if (!link || !entityId || !can(link.permission)) return undefined
  return link.href(entityId)
}
